-- M4: declarations, rest days, "too light" flags and leave (requirements F2, F2b, F3, F3b, F4a).
-- Every rule lives here; Server Actions only validate input shape and pass it on. Each RPC
-- returns the activity_events it recorded so lib/notify can tell the right people.

-- ---------------------------------------------------------------------------
-- Helpers
-- ---------------------------------------------------------------------------

-- The current time for every rule. Normally now(); a test session can pin it with
-- `set app.now = '...'`. Only the database owner and server-side RPCs run SQL here: the API
-- never lets clients set settings, and these RPCs are executable by service_role only.
create function private.now()
returns timestamptz
language sql
stable
set search_path = ''
as $$
  select coalesce(nullif(current_setting('app.now', true), '')::timestamptz, pg_catalog.now());
$$;

-- "Today" follows the same clock.
create or replace function private.jst_today()
returns date
language sql
stable
set search_path = ''
as $$
  select (private.now() at time zone 'Asia/Tokyo')::date;
$$;

-- Sunday that starts the week containing `d` (weeks run Sunday-Saturday, like settlements).
create function private.week_start(d date)
returns date
language sql
immutable
set search_path = ''
as $$
  select d - extract(dow from d)::int;
$$;

create function private.require_member(p_user_id uuid)
returns void
language plpgsql
stable
set search_path = ''
as $$
begin
  if not exists (select 1 from public.profiles where id = p_user_id and deactivated_at is null) then
    raise exception 'not_a_member' using errcode = 'P0001';
  end if;
end;
$$;

-- On leave that day: approved before the day began, inside the period, and not cut short.
create function private.is_on_leave(p_user_id uuid, p_date date)
returns boolean
language sql
stable
set search_path = ''
as $$
  select exists (
    select 1 from public.leave_requests l
    where l.user_id = p_user_id
      and l.approved_at is not null
      and l.approved_at < private.day_at(p_date, time '00:00')
      and p_date between l.start_date and l.end_date
      and (l.cancelled_from is null or p_date < l.cancelled_from)
  );
$$;

create function private.is_rest_day(p_user_id uuid, p_date date)
returns boolean
language sql
stable
set search_path = ''
as $$
  select exists (select 1 from public.rest_days where user_id = p_user_id and date = p_date);
$$;

-- Who reviews something `p_user_id` asked for: every other active member not on leave today.
create function private.reviewers_for(p_user_id uuid)
returns setof uuid
language sql
stable
set search_path = ''
as $$
  select p.id from public.profiles p
  where p.id <> p_user_id
    and p.deactivated_at is null
    and not private.is_on_leave(p.id, private.jst_today())
  order by p.created_at;
$$;

-- One penalty per study day (dedupe_key), waived while the member is in the trial week.
create function private.add_penalty(p_user_id uuid, p_study_log_id uuid, p_reason text, p_points int)
returns public.penalties
language plpgsql
set search_path = ''
as $$
declare
  added public.penalties;
begin
  if p_points <= 0 then
    return null;
  end if;
  insert into public.penalties (user_id, study_log_id, dedupe_key, points, reason, waived)
  select p_user_id, p_study_log_id, 'log:' || p_study_log_id, p_points, p_reason,
         case when p.trial_ends_at > private.now() then 'trial' end
  from public.profiles p where p.id = p_user_id
  on conflict (dedupe_key) do nothing
  returning * into added;
  return added;
end;
$$;

