do $$
declare
  fn text;
begin
  foreach fn in array array[
    'private.now()', 'private.week_start(date)', 'private.require_member(uuid)', 'private.is_on_leave(uuid, date)',
    'private.is_rest_day(uuid, date)', 'private.reviewers_for(uuid)',
    'private.add_penalty(uuid, uuid, text, int)',
    'public.declare_goal(uuid, text, time, text)', 'public.flag_declaration(uuid, uuid, text)',
    'public.revise_declaration(uuid, uuid, text)', 'public.expire_revisions()',
    'public.register_rest_day(uuid, date)', 'public.cancel_rest_day(uuid, date)',
    'public.request_leave(uuid, date, date, text)', 'public.cancel_leave(uuid, uuid)',
    'public.cast_review(uuid, text, uuid, text, text)', 'public.expire_reviews()'
  ] loop
    execute format('revoke all on function %s from public, anon, authenticated', fn);
    execute format('grant execute on function %s to service_role', fn);
  end loop;
end;
$$;
